import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { setCustomHome } from '../src/core/detector.js';
import { runDoctor } from '../src/core/doctor.js';
import {
  createJunction,
  ensureDir,
  isJunctionOrSymlink,
  safeWriteFile,
} from '../src/utils/fs.js';

describe('doctor', () => {
  let tmpDir: string;
  let homeDir: string;
  let hubDir: string;

  function setupHealthySandbox(home: string, hub: string) {
    // 1. Hub Manifest
    safeWriteFile(
      path.join(hub, 'agenthub.json'),
      JSON.stringify(
        {
          version: '0.1.0',
          platforms: {
            claude: { enabled: true },
            antigravity: { enabled: true },
            codex: { enabled: true },
            cursor: { enabled: true },
            windsurf: { enabled: true },
          },
        },
        null,
        2
      )
    );

    // 2. Hub Rules
    const rules = [
      'common.md',
      'code-tools.md',
      'handoffs.md',
      'overrides/agy.md',
      'overrides/claude.md',
      'overrides/codex.md',
      'overrides/cursor.md',
      'overrides/windsurf.md',
    ];
    for (const rule of rules) {
      safeWriteFile(path.join(hub, 'rules', rule), `# Rule: ${rule}`);
    }

    // 3. Hub Skills
    const skillDir = path.join(hub, 'skills', 'demo-skill');
    safeWriteFile(
      path.join(skillDir, 'SKILL.md'),
      '---\nname: demo-skill\ndescription: Demo skill description\n---\n# Demo'
    );
    safeWriteFile(
      path.join(skillDir, 'agents', 'openai.yaml'),
      'interface:\n  display_name: "Demo Skill"\n'
    );

    // 4. Hub MCP
    safeWriteFile(
      path.join(hub, 'mcp', 'servers.json'),
      JSON.stringify(
        {
          mcpServers: {
            'test-srv': {
              command: 'node',
              args: ['srv.js'],
            },
          },
        },
        null,
        2
      )
    );

    // 5. Claude
    ensureDir(path.join(home, '.claude'));
    createJunction(path.join(hub, 'skills'), path.join(home, '.claude', 'skills'));
    safeWriteFile(
      path.join(home, '.claude', 'CLAUDE.md'),
      '<!-- AUTOGENERATED BY AGENTRC - DO NOT EDIT DIRECTLY. EDIT IN ~/.agentrc/ -->\n\n@rules'
    );
    safeWriteFile(
      path.join(home, '.claude.json'),
      JSON.stringify(
        {
          mcpServers: {
            'test-srv': {
              command: 'node',
              args: ['srv.js'],
              type: 'stdio',
            },
          },
        },
        null,
        2
      )
    );

    // 6. Gemini / Antigravity
    ensureDir(path.join(home, '.gemini', 'config'));
    const hubSkillsPosix = path.resolve(hub, 'skills').replace(/\\/g, '/');
    safeWriteFile(
      path.join(home, '.gemini', 'config', 'skills.json'),
      JSON.stringify(
        {
          entries: [{ path: hubSkillsPosix }],
        },
        null,
        2
      )
    );
    safeWriteFile(
      path.join(home, '.gemini', 'GEMINI.md'),
      '<!-- AUTOGENERATED BY AGENTRC - DO NOT EDIT DIRECTLY. EDIT IN ~/.agentrc/ -->\n\nGemini rules'
    );
    safeWriteFile(
      path.join(home, '.gemini', 'config', 'mcp_config.json'),
      JSON.stringify(
        {
          mcpServers: {
            'test-srv': {
              command: 'node',
              args: ['srv.js'],
              type: 'stdio',
            },
          },
        },
        null,
        2
      )
    );

    // 7. Codex
    ensureDir(path.join(home, '.codex'));
    createJunction(path.join(hub, 'skills'), path.join(home, '.codex', 'skills'));
    safeWriteFile(
      path.join(home, '.codex', 'AGENTS.md'),
      '<!-- AUTOGENERATED BY AGENTRC - DO NOT EDIT DIRECTLY. EDIT IN ~/.agentrc/ -->\n\nCodex rules'
    );

    // 8. Cursor
    ensureDir(path.join(home, '.cursor', 'rules'));
    createJunction(path.join(hub, 'skills'), path.join(home, '.cursor', 'skills'));
    safeWriteFile(
      path.join(home, '.cursor', 'rules', 'agentrc.mdc'),
      '---\ndescription: Cursor rules\n---\nGlobal rules'
    );

    // 9. Windsurf
    ensureDir(path.join(home, '.windsurf', 'memories'));
    createJunction(path.join(hub, 'skills'), path.join(home, '.windsurf', 'skills'));
    safeWriteFile(
      path.join(home, '.windsurf', 'memories', 'global_rules.md'),
      'Windsurf rules'
    );
  }

  beforeEach(() => {
    tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'agenthub-doctor-test-'));
    homeDir = path.join(tmpDir, 'home');
    hubDir = path.join(tmpDir, 'hub');
    ensureDir(homeDir);
    ensureDir(hubDir);
    setCustomHome(homeDir, hubDir);
  });

  afterEach(() => {
    setCustomHome(null, null);
    try {
      fs.rmSync(tmpDir, { recursive: true, force: true });
    } catch {
      // ignore cleanup errors
    }
  });

  it('reports PASS on a completely healthy sandbox with all platforms', () => {
    setupHealthySandbox(homeDir, hubDir);

    const report = runDoctor({ homeDir, hubDir });

    expect(report.status).toBe('PASS');
    expect(report.issues).toHaveLength(0);
    expect(report.passed_checks).toHaveLength(13);
    expect(report.repairs).toHaveLength(0);

    expect(report.passed_checks).toContain('Hub manifest exists');
    expect(report.passed_checks).toContain('Claude skills junction verified');
    expect(report.passed_checks).toContain(
      'Antigravity skills configuration verified'
    );
    expect(report.passed_checks).toContain('Gemini rules verified');
    expect(report.passed_checks).toContain('Claude rules verified');
    expect(report.passed_checks).toContain('Codex rules verified');
    expect(report.passed_checks).toContain('Codex skills junction verified');
    expect(report.passed_checks).toContain('Codex skill manifests verified');
    expect(report.passed_checks).toContain('Cursor skills junction verified');
    expect(report.passed_checks).toContain('Cursor rules verified');
    expect(report.passed_checks).toContain('Windsurf skills junction verified');
    expect(report.passed_checks).toContain('Windsurf rules verified');
    expect(report.passed_checks).toContain('MCP registry synchronized');
  });

  it('detects missing manifest and reports WARN', () => {
    setupHealthySandbox(homeDir, hubDir);
    fs.unlinkSync(path.join(hubDir, 'agenthub.json'));

    const report = runDoctor({ homeDir, hubDir });

    expect(report.status).toBe('WARN');
    expect(
      report.issues.some((issue) => issue.includes('Hub manifest missing'))
    ).toBe(true);
  });

  it('detects severed or missing skills junctions', () => {
    setupHealthySandbox(homeDir, hubDir);

    // Sever Claude skills junction by removing it
    fs.rmSync(path.join(homeDir, '.claude', 'skills'), {
      recursive: true,
      force: true,
    });
    // Break Codex skills junction by replacing with a regular file
    fs.rmSync(path.join(homeDir, '.codex', 'skills'), {
      recursive: true,
      force: true,
    });
    safeWriteFile(path.join(homeDir, '.codex', 'skills'), 'not a link');

    const report = runDoctor({ homeDir, hubDir });

    expect(report.status).toBe('WARN');
    expect(
      report.issues.some((issue) =>
        issue.includes('Claude skills junction missing or invalid')
      )
    ).toBe(true);
    expect(
      report.issues.some((issue) =>
        issue.includes('Codex skills junction missing or invalid')
      )
    ).toBe(true);
  });

  it('detects missing or unmanaged rules files', () => {
    setupHealthySandbox(homeDir, hubDir);

    // Unmanaged Gemini rules (missing header guard)
    safeWriteFile(
      path.join(homeDir, '.gemini', 'GEMINI.md'),
      'User custom unmanaged notes'
    );
    // Missing Claude rules
    fs.unlinkSync(path.join(homeDir, '.claude', 'CLAUDE.md'));

    const report = runDoctor({ homeDir, hubDir });

    expect(report.status).toBe('WARN');
    expect(
      report.issues.some((issue) =>
        issue.includes('Gemini rules missing header guard')
      )
    ).toBe(true);
    expect(
      report.issues.some((issue) => issue.includes('Claude rules file missing'))
    ).toBe(true);
  });

  it('detects missing Codex skill manifests', () => {
    setupHealthySandbox(homeDir, hubDir);

    // Add a skill without agents/openai.yaml
    const unmanifested = path.join(hubDir, 'skills', 'new-unmanifested-skill');
    safeWriteFile(
      path.join(unmanifested, 'SKILL.md'),
      '---\nname: new-unmanifested-skill\n---\n# Unmanifested'
    );

    const report = runDoctor({ homeDir, hubDir });

    expect(report.status).toBe('WARN');
    expect(
      report.issues.some((issue) =>
        issue.includes('Codex skill manifest missing')
      )
    ).toBe(true);
  });

  it('detects unsynchronized MCP registry', () => {
    setupHealthySandbox(homeDir, hubDir);

    // Add new server to hub that is not configured in Claude or Gemini
    const mcpData = {
      mcpServers: {
        'test-srv': { command: 'node', args: ['srv.js'] },
        'unregistered-srv': { command: 'python', args: ['srv.py'] },
      },
    };
    safeWriteFile(
      path.join(hubDir, 'mcp', 'servers.json'),
      JSON.stringify(mcpData, null, 2)
    );

    const report = runDoctor({ homeDir, hubDir });

    expect(report.status).toBe('WARN');
    expect(
      report.issues.some((issue) => issue.includes('MCP registry out of sync'))
    ).toBe(true);
  });

  it('performs full --fix auto-repair across all platforms and assets', () => {
    setupHealthySandbox(homeDir, hubDir);

    // 1. Break Claude junction
    fs.rmSync(path.join(homeDir, '.claude', 'skills'), {
      recursive: true,
      force: true,
    });

    // 2. Delete Gemini rules
    fs.unlinkSync(path.join(homeDir, '.gemini', 'GEMINI.md'));

    // 3. Add skill missing Codex manifest
    const extraSkill = path.join(hubDir, 'skills', 'auto-repair-skill');
    safeWriteFile(
      path.join(extraSkill, 'SKILL.md'),
      '---\nname: auto-repair-skill\ndescription: Auto repaired skill\n---\n# Content'
    );

    // 4. Add new MCP server to hub so platforms are drifted/out of sync
    const mcpData = {
      mcpServers: {
        'test-srv': { command: 'node', args: ['srv.js'] },
        'fresh-mcp': { command: 'bun', args: ['fresh.ts'] },
      },
    };
    safeWriteFile(
      path.join(hubDir, 'mcp', 'servers.json'),
      JSON.stringify(mcpData, null, 2)
    );

    // Verify issues detected initially without --fix
    const preCheck = runDoctor({ homeDir, hubDir });
    expect(preCheck.status).toBe('WARN');
    expect(preCheck.issues.length).toBeGreaterThan(0);

    // Run doctor with --fix
    const fixResult = runDoctor({ fix: true, homeDir, hubDir });

    // Verify repairs were recorded
    expect(fixResult.repairs.length).toBeGreaterThan(0);
    expect(fixResult.repairs).toContain(
      'Ran link_skills and projections across all platforms.'
    );

    // Verify status is now PASS and issues is empty
    expect(fixResult.status).toBe('PASS');
    expect(fixResult.issues).toHaveLength(0);

    // Verify disk state:
    // 1. Claude skills junction restored
    const claudeSkills = path.join(homeDir, '.claude', 'skills');
    expect(fs.existsSync(claudeSkills)).toBe(true);
    expect(isJunctionOrSymlink(claudeSkills)).toBe(true);

    // 2. Gemini rules re-projected with header guard
    const geminiRules = path.join(homeDir, '.gemini', 'GEMINI.md');
    expect(fs.existsSync(geminiRules)).toBe(true);
    expect(fs.readFileSync(geminiRules, 'utf-8')).toContain(
      'AUTOGENERATED BY AGENTRC'
    );

    // 3. Codex manifest generated for auto-repair-skill
    const codexManifest = path.join(extraSkill, 'agents', 'openai.yaml');
    expect(fs.existsSync(codexManifest)).toBe(true);
    expect(fs.readFileSync(codexManifest, 'utf-8')).toContain(
      'Auto Repair Skill'
    );

    // 4. MCP servers synchronized to Claude and Gemini
    const claudeJson = JSON.parse(
      fs.readFileSync(path.join(homeDir, '.claude.json'), 'utf-8')
    );
    expect(claudeJson.mcpServers['fresh-mcp']).toBeDefined();

    const geminiMcp = JSON.parse(
      fs.readFileSync(
        path.join(homeDir, '.gemini', 'config', 'mcp_config.json'),
        'utf-8'
      )
    );
    expect(geminiMcp.mcpServers['fresh-mcp']).toBeDefined();
  });

  it('detects corrupt MCP JSON files and reports explicit issues', () => {
    setupHealthySandbox(homeDir, hubDir);

    // Corrupt hub servers.json
    safeWriteFile(path.join(hubDir, 'mcp', 'servers.json'), '{ corrupt hub json');
    const hubReport = runDoctor({ homeDir, hubDir });
    expect(hubReport.status).toBe('WARN');
    expect(
      hubReport.issues.some((issue) =>
        issue.includes('MCP hub registry file is invalid or corrupt JSON')
      )
    ).toBe(true);

    // Restore hub, corrupt Claude .claude.json
    safeWriteFile(
      path.join(hubDir, 'mcp', 'servers.json'),
      JSON.stringify({ mcpServers: {} })
    );
    safeWriteFile(path.join(homeDir, '.claude.json'), '{ corrupt claude json');
    const claudeReport = runDoctor({ homeDir, hubDir });
    expect(claudeReport.status).toBe('WARN');
    expect(
      claudeReport.issues.some((issue) =>
        issue.includes('Claude MCP configuration file is invalid or corrupt JSON')
      )
    ).toBe(true);

    // Restore Claude, corrupt Gemini mcp_config.json
    safeWriteFile(
      path.join(homeDir, '.claude.json'),
      JSON.stringify({ mcpServers: {} })
    );
    safeWriteFile(
      path.join(homeDir, '.gemini', 'config', 'mcp_config.json'),
      '{ corrupt gemini json'
    );
    const geminiReport = runDoctor({ homeDir, hubDir });
    expect(geminiReport.status).toBe('WARN');
    expect(
      geminiReport.issues.some((issue) =>
        issue.includes('Gemini MCP configuration file is invalid or corrupt JSON')
      )
    ).toBe(true);
  });

  it('self-heals missing servers.json in doctor --fix', () => {
    setupHealthySandbox(homeDir, hubDir);

    const mcpServersFile = path.join(hubDir, 'mcp', 'servers.json');
    fs.unlinkSync(mcpServersFile);
    expect(fs.existsSync(mcpServersFile)).toBe(false);

    const preCheck = runDoctor({ homeDir, hubDir });
    expect(preCheck.status).toBe('WARN');
    expect(
      preCheck.issues.some((issue) => issue.includes('MCP hub registry missing'))
    ).toBe(true);

    const fixResult = runDoctor({ fix: true, homeDir, hubDir });
    expect(fs.existsSync(mcpServersFile)).toBe(true);
    expect(fixResult.status).toBe('PASS');
    expect(fixResult.issues).toHaveLength(0);
    expect(fixResult.passed_checks).toContain('MCP registry synchronized');
  });

  it('respects custom target directories for Cursor and Windsurf during --fix', () => {
    setupHealthySandbox(homeDir, hubDir);

    const customCursor = path.join(tmpDir, 'custom-cursor');
    const customWindsurf = path.join(tmpDir, 'custom-windsurf');
    ensureDir(customCursor);
    ensureDir(customWindsurf);

    safeWriteFile(
      path.join(hubDir, 'agenthub.json'),
      JSON.stringify(
        {
          version: '0.1.0',
          platforms: {
            cursor: { enabled: true, path: customCursor },
            windsurf: { enabled: true, path: customWindsurf },
          },
        },
        null,
        2
      )
    );

    // Remove home/.cursor and home/.windsurf to ensure only custom targets are used
    fs.rmSync(path.join(homeDir, '.cursor'), { recursive: true, force: true });
    fs.rmSync(path.join(homeDir, '.windsurf'), { recursive: true, force: true });

    const fixResult = runDoctor({ fix: true, homeDir, hubDir });
    expect(fixResult.status).toBe('PASS');

    // Verify custom cursor has skills junction and rules
    expect(isJunctionOrSymlink(path.join(customCursor, 'skills'))).toBe(true);
    expect(fs.existsSync(path.join(customCursor, 'rules', 'agentrc.mdc'))).toBe(true);

    // Verify custom windsurf has skills junction and rules
    expect(isJunctionOrSymlink(path.join(customWindsurf, 'skills'))).toBe(true);
    expect(
      fs.existsSync(path.join(customWindsurf, 'memories', 'global_rules.md'))
    ).toBe(true);
  });
});
