/**
 * Markdown AST chunker for agenthub.
 * Parses markdown files into hierarchical section chunks with normalized hashing,
 * fenced code block awareness, and drift diffing.
 */

import { createHash } from 'node:crypto';

export interface MarkdownChunk {
  header: string;           // Header text without leading # or trailing adorned #
  level: number;            // Heading level (0 for prelude, 1 for #, 2 for ##, ..., 6 for ######)
  path: string[];           // Hierarchical header stack path, e.g. ["Section", "Subsection"]
  content: string;          // Body text excluding the heading line itself
  raw: string;              // Full raw section text including heading and newlines
  normalizedHash: string;   // SHA-256 hex digest of normalized content
  codeBlocks: string[];     // Raw code fence blocks inside this section
}

export interface ChunkDiff {
  identical: MarkdownChunk[];
  modified: Array<{ source: MarkdownChunk; target: MarkdownChunk }>;
  added: MarkdownChunk[];
  removed: MarkdownChunk[];
}

/**
 * Normalizes content for deterministic hashing:
 * - Normalizes \r\n and \r to \n
 * - Strips trailing whitespace on each line
 * - Strips leading and trailing blank lines / whitespace
 */
export function normalizeContent(text: string): string {
  const normalized = text.replace(/\r\n/g, '\n').replace(/\r/g, '\n');
  const lines = normalized.split('\n');
  const stripped = lines.map((line) => line.replace(/\s+$/, ''));
  return stripped.join('\n').trim();
}

/**
 * Computes SHA-256 hex digest of normalized content.
 */
export function computeNormalizedHash(text: string): string {
  return createHash('sha256').update(normalizeContent(text), 'utf-8').digest('hex');
}

/**
 * Parses markdown text into hierarchical MarkdownChunk objects.
 * - Honors fenced code blocks (``` and ~~~) so '#' inside code blocks are not headers.
 * - Strips or ignores HTML comments (like agentrc autogenerated guards).
 * - Preserves prelude text as a level 0 chunk if non-empty.
 */
export function parseMarkdownChunks(markdownText: string): MarkdownChunk[] {
  const text = markdownText.replace(/\r\n/g, '\n').replace(/\r/g, '\n');
  const lines = text.split('\n');

  const chunks: MarkdownChunk[] = [];

  let inCodeBlock = false;
  let fenceChar = '';
  let fenceLen = 0;
  let currentCodeBlockLines: string[] = [];

  const headerStack: Array<[number, string]> = [];

  let currentHeader: string | null = null;
  let currentLevel = 0;
  let currentContentLines: string[] = [];
  let currentRawLines: string[] = [];
  let currentCodeBlocks: string[] = [];

  function finalizeCurrentChunk() {
    if (currentHeader === null) {
      // Level 0 prelude
      const rawText = currentRawLines.join('\n');
      const strippedPrelude = rawText.replace(/<!--[\s\S]*?-->/g, '').trim();
      if (strippedPrelude) {
        const contentText = strippedPrelude;
        const nhash = computeNormalizedHash(contentText);
        const cleanRaw = rawText.replace(/<!--[\s\S]*?-->\n*/g, '').trim();
        chunks.push({
          header: '',
          level: 0,
          path: [],
          content: contentText,
          raw: cleanRaw ? cleanRaw + '\n' : '',
          normalizedHash: nhash,
          codeBlocks: [...currentCodeBlocks],
        });
      }
    } else {
      const contentText = currentContentLines.join('\n').replace(/\s+$/, '');
      const rawText = currentRawLines.join('\n');
      const pathArray = headerStack.map((s) => s[1]);
      const nhash = computeNormalizedHash(contentText);
      chunks.push({
        header: currentHeader,
        level: currentLevel,
        path: pathArray,
        content: contentText,
        raw: rawText,
        normalizedHash: nhash,
        codeBlocks: [...currentCodeBlocks],
      });
    }

    currentContentLines = [];
    currentRawLines = [];
    currentCodeBlocks = [];
  }

  const fencePattern = /^(\s*)(`{3,}|~{3,})(.*)$/;
  const headerPattern = /^(#{1,6})\s+(.*)$/;

  for (const line of lines) {
    if (inCodeBlock) {
      currentRawLines.push(line);
      currentContentLines.push(line);
      currentCodeBlockLines.push(line);
      const closeMatch = line.match(/^\s*(`{3,}|~{3,})\s*$/);
      if (closeMatch) {
        const cDel = closeMatch[1];
        if (cDel[0] === fenceChar && cDel.length >= fenceLen) {
          inCodeBlock = false;
          currentCodeBlocks.push(currentCodeBlockLines.join('\n'));
          currentCodeBlockLines = [];
        }
      }
      continue;
    }

    const fenceMatch = line.match(fencePattern);
    if (fenceMatch && !fenceMatch[3].includes(fenceMatch[2][0])) {
      inCodeBlock = true;
      fenceChar = fenceMatch[2][0];
      fenceLen = fenceMatch[2].length;
      currentRawLines.push(line);
      currentContentLines.push(line);
      currentCodeBlockLines = [line];
      continue;
    }

    const headerMatch = line.match(headerPattern);
    if (headerMatch) {
      finalizeCurrentChunk();

      const level = headerMatch[1].length;
      const rawHeader = headerMatch[2].trim();
      const headerText = rawHeader.replace(/\s+#+\s*$/, '').trim();

      while (headerStack.length > 0 && headerStack[headerStack.length - 1][0] >= level) {
        headerStack.pop();
      }
      headerStack.push([level, headerText]);

      currentHeader = headerText;
      currentLevel = level;
      currentRawLines = [line];
      currentContentLines = [];
      currentCodeBlocks = [];
    } else {
      currentRawLines.push(line);
      currentContentLines.push(line);
    }
  }

  if (inCodeBlock && currentCodeBlockLines.length > 0) {
    currentCodeBlocks.push(currentCodeBlockLines.join('\n'));
    currentCodeBlockLines = [];
    inCodeBlock = false;
  }

  finalizeCurrentChunk();
  return chunks;
}

/**
 * Compares two lists of chunks by header path and normalizedHash.
 * Key chunks by chunk.path.join(" / ").
 * Returns:
 * - identical: list of chunks present in both with identical normalizedHash
 * - modified: list of { source, target } for chunks with same path but differing hashes
 * - added: list of chunks present in source but missing from target
 * - removed: list of chunks present in target but missing from source
 */
export function diffChunks(
  sourceChunks: MarkdownChunk[],
  targetChunks: MarkdownChunk[],
): ChunkDiff {
  const targetByPath = new Map<string, MarkdownChunk>();
  for (const c of targetChunks) {
    targetByPath.set(c.path.join(' / '), c);
  }

  const sourceByPath = new Map<string, MarkdownChunk>();
  for (const c of sourceChunks) {
    sourceByPath.set(c.path.join(' / '), c);
  }

  const identical: MarkdownChunk[] = [];
  const modified: Array<{ source: MarkdownChunk; target: MarkdownChunk }> = [];
  const added: MarkdownChunk[] = [];
  const removed: MarkdownChunk[] = [];

  for (const s of sourceChunks) {
    const key = s.path.join(' / ');
    const t = targetByPath.get(key);
    if (t) {
      if (s.normalizedHash === t.normalizedHash) {
        identical.push(s);
      } else {
        modified.push({ source: s, target: t });
      }
    } else {
      added.push(s);
    }
  }

  for (const t of targetChunks) {
    const key = t.path.join(' / ');
    if (!sourceByPath.has(key)) {
      removed.push(t);
    }
  }

  return {
    identical,
    modified,
    added,
    removed,
  };
}
