/**
 * Deterministic projector for rules and subagents.
 * Compiles universal rules and agent templates into host-specific manifests.
 */

import fs from 'node:fs';
import path from 'node:path';
import yaml from 'yaml';
import { safeWriteFile } from '../utils/fs.js';
import { getHomeDir, getHubDir } from './detector.js';

export const HEADER_GUARD = '<!-- AUTOGENERATED BY AGENTRC - DO NOT EDIT DIRECTLY. EDIT IN ~/.agentrc/ -->';

export const PLATFORM_RULE_FILES: Record<string, string[]> = {
  gemini: ['common.md', 'code-tools.md', 'handoffs.md', 'overrides/agy.md'],
  claude: ['common.md', 'code-tools.md', 'handoffs.md', 'overrides/claude.md'],
  codex: ['common.md', 'code-tools.md', 'handoffs.md', 'overrides/codex.md'],
  cursor: ['common.md', 'code-tools.md', 'handoffs.md', 'overrides/cursor.md'],
  windsurf: ['common.md', 'code-tools.md', 'handoffs.md', 'overrides/windsurf.md'],
};

export interface AgentFrontmatter {
  name?: string;
  description?: string;
  tier?: string;
  effort?: string;
  mode?: string;
  enable_write_tools?: string;
  [key: string]: string | undefined;
}

export interface ParsedAgentTemplate {
  meta: AgentFrontmatter;
  body: string;
}

export interface ProjectResult {
  success: boolean;
  message: string;
}

export interface ProjectSubagentsResult {
  success: boolean;
  results: string[];
}

export interface ProjectRulesResult {
  success: boolean;
  messages: string[];
}

export interface ProjectOptions {
  useImports?: boolean;
  homeDir?: string;
  hubDir?: string;
  cursorDir?: string;
  windsurfDir?: string;
}

/**
 * Parses YAML frontmatter and body from markdown content.
 * Splits on frontmatter delimiters using /^---\r?\n([\s\S]*?)\r?\n---(?:\r?\n([\s\S]*))?$/.
 * Parses the YAML block using yaml.parse().
 * If YAML parsing fails or no frontmatter block, returns { meta: {}, body: content }.
 */
export function parseFrontmatter(content: string): ParsedAgentTemplate {
  const match = content.match(/^---\r?\n([\s\S]*?)\r?\n---(?:\r?\n([\s\S]*))?$/);
  if (!match) {
    return { meta: {}, body: content };
  }

  const yamlText = match[1];
  const body = match[2] ?? '';

  let parsed: unknown;
  try {
    parsed = yaml.parse(yamlText);
  } catch {
    return { meta: {}, body: content };
  }

  const meta: AgentFrontmatter = {};
  if (parsed && typeof parsed === 'object' && !Array.isArray(parsed)) {
    for (const [key, val] of Object.entries(parsed)) {
      if (val !== undefined && val !== null) {
        meta[key] = typeof val === 'string' ? val.trim() : String(val);
      }
    }
  }

  return { meta, body };
}

/**
 * Scans hubDir/rules/addons/ for markdown rule files and returns relative paths (e.g. 'addons/xxx.md').
 */
export function getAddonRuleFiles(hubDir: string): string[] {
  const addonsDir = path.join(hubDir, 'rules', 'addons');
  try {
    if (!fs.existsSync(addonsDir) || !fs.statSync(addonsDir).isDirectory()) {
      return [];
    }
    return fs
      .readdirSync(addonsDir)
      .filter((f) => f.endsWith('.md') && !f.startsWith('.') && fs.statSync(path.join(addonsDir, f)).isFile())
      .sort()
      .map((f) => path.posix.join('addons', f));
  } catch {
    return [];
  }
}

function readPlatformRules(hubDir: string, fileList: string[]): string | null {
  const rulesDir = path.join(hubDir, 'rules');
  if (!fs.existsSync(rulesDir) || !fs.statSync(rulesDir).isDirectory()) {
    return null;
  }
  const parts: string[] = [HEADER_GUARD];
  for (const fileName of fileList) {
    const filePath = path.join(rulesDir, fileName);
    if (fs.existsSync(filePath) && fs.statSync(filePath).isFile()) {
      parts.push(fs.readFileSync(filePath, 'utf-8').trim());
    }
  }
  const addonFiles = getAddonRuleFiles(hubDir);
  for (const addonFile of addonFiles) {
    const filePath = path.join(rulesDir, addonFile);
    if (fs.existsSync(filePath) && fs.statSync(filePath).isFile()) {
      parts.push(fs.readFileSync(filePath, 'utf-8').trim());
    }
  }
  return parts.join('\n\n') + '\n';
}

/**
 * Projects global rules to Gemini (~/.gemini/GEMINI.md).
 * Removes ~/.gemini/config/GEMINI.md if it exists as a separate file to prevent duplication.
 */
export function projectGeminiRules(
  homeDir?: string,
  hubDir?: string
): ProjectResult {
  const home = homeDir || getHomeDir();
  const hub = hubDir || getHubDir();
  const rulesDir = path.join(hub, 'rules');

  const content = readPlatformRules(hub, PLATFORM_RULE_FILES.gemini);
  if (content === null) {
    return { success: false, message: `Rules directory not found: ${rulesDir}` };
  }

  const target1 = path.join(home, '.gemini', 'GEMINI.md');
  const target2 = path.join(home, '.gemini', 'config', 'GEMINI.md');

  safeWriteFile(target1, content);

  if (fs.existsSync(target2)) {
    try {
      let isSame = false;
      try {
        const real1 = fs.realpathSync(target1);
        const real2 = fs.realpathSync(target2);
        isSame =
          process.platform === 'win32'
            ? real1.toLowerCase() === real2.toLowerCase()
            : real1 === real2;
      } catch {
        isSame = false;
      }
      if (!isSame) {
        let isAutogenerated = false;
        try {
          const target2Content = fs.readFileSync(target2, 'utf-8');
          isAutogenerated =
            target2Content.includes('AUTOGENERATED BY AGENTRC') ||
            target2Content.includes('AUTOGENERATED BY AGENTHUB');
        } catch {
          // ignore read error
        }

        if (isAutogenerated) {
          fs.unlinkSync(target2);
        } else {
          const backupTarget = `${target2}.backup`;
          try {
            if (fs.existsSync(backupTarget)) {
              fs.unlinkSync(backupTarget);
            }
            fs.renameSync(target2, backupTarget);
          } catch {
            fs.copyFileSync(target2, backupTarget);
            fs.unlinkSync(target2);
          }
        }
      }
    } catch {
      // ignore unlink error
    }
  }

  return { success: true, message: `Projected GEMINI.md (${content.length} chars)` };
}

/**
 * Projects global rules to Claude (~/.claude/CLAUDE.md).
 * Defaults to modular @import syntax unless useImports is false.
 */
export function projectClaudeRules(options?: {
  useImports?: boolean;
  homeDir?: string;
  hubDir?: string;
}): ProjectResult {
  const useImports = options?.useImports ?? true;
  const home = options?.homeDir || getHomeDir();
  const hub = options?.hubDir || getHubDir();
  const rulesDir = path.join(hub, 'rules');
  const target = path.join(home, '.claude', 'CLAUDE.md');

  let content: string;
  if (useImports) {
    if (!fs.existsSync(rulesDir)) {
      return { success: false, message: `Rules directory not found: ${rulesDir}` };
    }
    const existingFiles = PLATFORM_RULE_FILES.claude.filter((f) =>
      fs.existsSync(path.join(rulesDir, f))
    );
    const addonFiles = getAddonRuleFiles(hub).filter((f) =>
      fs.existsSync(path.join(rulesDir, f))
    );
    if (existingFiles.length === 0 && addonFiles.length === 0) {
      return { success: false, message: `No rule files found to project in: ${rulesDir}` };
    }
    const allFiles = [...existingFiles, ...addonFiles];
    const importLines = allFiles.map((f) => {
      const p = path.join(rulesDir, f).replace(/\\/g, '/');
      return `@${p}`;
    });
    content = `${HEADER_GUARD}\n\n${importLines.join('\n')}\n`;
  } else {
    const rulesContent = readPlatformRules(hub, PLATFORM_RULE_FILES.claude);
    if (rulesContent === null) {
      return { success: false, message: `Rules directory not found: ${rulesDir}` };
    }
    content = rulesContent;
  }

  safeWriteFile(target, content);
  return { success: true, message: `Projected CLAUDE.md (${content.length} chars)` };
}

/**
 * Projects global rules to Codex (~/.codex/AGENTS.md) and creates a ChatGPT export.
 */
export function projectCodexRules(
  homeDir?: string,
  hubDir?: string
): ProjectResult {
  const home = homeDir || getHomeDir();
  const hub = hubDir || getHubDir();
  const rulesDir = path.join(hub, 'rules');

  const content = readPlatformRules(hub, PLATFORM_RULE_FILES.codex);
  if (content === null) {
    return { success: false, message: `Rules directory not found: ${rulesDir}` };
  }

  const target = path.join(home, '.codex', 'AGENTS.md');
  safeWriteFile(target, content);

  const chatgptExport = path.join(hub, 'export', 'chatgpt_custom_instructions.md');
  safeWriteFile(chatgptExport, content);

  return {
    success: true,
    message: `Projected AGENTS.md and ChatGPT export (${content.length} chars)`,
  };
}

/**
 * Projects global rules to Cursor if detected (~/.cursor/rules/agentrc.mdc and ~/.cursorrules).
 */
export function projectCursorRules(
  cursorDir?: string,
  homeDir?: string,
  hubDir?: string
): ProjectResult {
  const home = homeDir || getHomeDir();
  const hub = hubDir || getHubDir();
  const targetDir = cursorDir || path.join(home, '.cursor');

  const targetDirExists = fs.existsSync(targetDir) && fs.statSync(targetDir).isDirectory();
  const cursorRulesFile = path.join(home, '.cursorrules');
  const cursorRulesExists = fs.existsSync(cursorRulesFile) && fs.statSync(cursorRulesFile).isFile();

  if (!targetDirExists && !cursorRulesExists) {
    return { success: true, message: 'Cursor not detected/connected; skipped projection' };
  }

  const rulesDir = path.join(hub, 'rules');
  const content = readPlatformRules(hub, PLATFORM_RULE_FILES.cursor);
  if (content === null) {
    return { success: false, message: `Rules directory not found: ${rulesDir}` };
  }

  const mdcFile = path.join(targetDir, 'rules', 'agentrc.mdc');
  const mdcContent = `---\ndescription: Global multi-assistant heuristics and engineering guidelines\nglobs: *\n---\n\n${content}`;
  safeWriteFile(mdcFile, mdcContent);

  safeWriteFile(cursorRulesFile, content);

  return { success: true, message: `Projected Cursor rules (${content.length} chars)` };
}

/**
 * Projects global rules to Windsurf if detected (targetDir/memories/global_rules.md and ~/.windsurfrules).
 */
export function projectWindsurfRules(
  windsurfDir?: string,
  homeDir?: string,
  hubDir?: string
): ProjectResult {
  const home = homeDir || getHomeDir();
  const hub = hubDir || getHubDir();

  let targetDir = windsurfDir;
  if (!targetDir) {
    const codeiumDir = path.join(home, '.codeium', 'windsurf');
    if (fs.existsSync(codeiumDir) && fs.statSync(codeiumDir).isDirectory()) {
      targetDir = codeiumDir;
    } else {
      targetDir = path.join(home, '.windsurf');
    }
  }

  const targetDirExists = fs.existsSync(targetDir) && fs.statSync(targetDir).isDirectory();
  const windsurfRulesFile = path.join(home, '.windsurfrules');
  const windsurfRulesExists = fs.existsSync(windsurfRulesFile) && fs.statSync(windsurfRulesFile).isFile();

  if (!targetDirExists && !windsurfRulesExists) {
    return { success: true, message: 'Windsurf not detected/connected; skipped projection' };
  }

  const rulesDir = path.join(hub, 'rules');
  const content = readPlatformRules(hub, PLATFORM_RULE_FILES.windsurf);
  if (content === null) {
    return { success: false, message: `Rules directory not found: ${rulesDir}` };
  }

  const globalRulesFile = path.join(targetDir, 'memories', 'global_rules.md');
  safeWriteFile(globalRulesFile, content);

  safeWriteFile(windsurfRulesFile, content);

  return { success: true, message: `Projected Windsurf rules (${content.length} chars)` };
}

/**
 * Projects custom subagents from hubDir/agents/*.md to Gemini and Claude subagent configurations.
 */
export function projectSubagents(
  homeDir?: string,
  hubDir?: string
): ProjectSubagentsResult {
  const home = homeDir || getHomeDir();
  const hub = hubDir || getHubDir();
  const agentsDir = path.join(hub, 'agents');

  if (!fs.existsSync(agentsDir) || !fs.statSync(agentsDir).isDirectory()) {
    return { success: false, results: ['No agents directory in hub'] };
  }

  const geminiAgentsDir = path.join(home, '.gemini', 'config', 'agents');
  const claudeAgentsDir = path.join(home, '.claude', 'agents');

  const files = fs.readdirSync(agentsDir).filter((f) => f.endsWith('.md')).sort();
  const results: string[] = [];

  for (const fileName of files) {
    const filePath = path.join(agentsDir, fileName);
    if (!fs.statSync(filePath).isFile()) continue;

    const content = fs.readFileSync(filePath, 'utf-8');
    const { meta, body } = parseFrontmatter(content);

    const baseName = path.parse(fileName).name;
    const name = meta.name || baseName;
    const desc = meta.description || '';
    const tier = meta.tier || 'inherit';
    const effort = meta.effort || 'medium';
    const mode = meta.mode || 'read-write';
    const enableWriteTools = meta.enable_write_tools === 'true';

    const formattedBody =
      body.length === 0
        ? '\n'
        : body.startsWith('\n') || body.startsWith('\r\n')
          ? body
          : `\n${body}`;

    // 1. Gemini subagent
    const agyModel =
      tier === 'pro' || tier === 'smart'
        ? 'pro'
        : tier === 'fast' || tier === 'flash'
          ? 'flash'
          : 'inherit';

    const agyFm: string[] = [
      '---',
      `name: ${name}`,
      `description: ${desc}`,
      `model: ${agyModel}`,
      `effort: ${effort}`,
      'subagent: true',
    ];

    if (mode === 'read-write' || enableWriteTools) {
      agyFm.push(
        'tools:',
        '  - run_command',
        '  - write_file',
        '  - edit_file',
        '  - read_file'
      );
    } else {
      agyFm.push(
        'tools:',
        '  - run_command',
        '  - read_file'
      );
    }
    agyFm.push('---');
    const agyContent = agyFm.join('\n') + formattedBody;
    safeWriteFile(path.join(geminiAgentsDir, `${name}.md`), agyContent);

    // 2. Claude subagent
    const claudeModel = tier === 'fast' || tier === 'inherit' ? 'haiku' : 'sonnet';
    const claudeTools =
      mode === 'read-write'
        ? 'Bash, Read, Edit, Write, Glob, Grep'
        : 'Bash, Read, Glob, Grep';

    const claudeFm: string[] = [
      '---',
      `name: ${name}`,
      `description: ${desc}`,
      `model: ${claudeModel}`,
      `effort: ${effort}`,
      `tools: ${claudeTools}`,
      '---',
    ];
    const claudeContent = claudeFm.join('\n') + formattedBody;
    safeWriteFile(path.join(claudeAgentsDir, `${name}.md`), claudeContent);

    results.push(`Projected subagent: ${name}`);
  }

  return { success: true, results };
}

/**
 * Projects all rules across supported platforms.
 */
export function projectRules(options?: ProjectOptions): ProjectRulesResult {
  const home = options?.homeDir || getHomeDir();
  const hub = options?.hubDir || getHubDir();
  const useImports = options?.useImports ?? true;

  const results = [
    projectGeminiRules(home, hub),
    projectClaudeRules({ useImports, homeDir: home, hubDir: hub }),
    projectCodexRules(home, hub),
    projectCursorRules(options?.cursorDir, home, hub),
    projectWindsurfRules(options?.windsurfDir, home, hub),
  ];

  const allSuccess = results.every((r) => r.success);
  const messages = results.map((r) => r.message);

  return { success: allSuccess, messages };
}

/**
 * Runs full projection (rules + subagents).
 */
export function projectAll(options?: ProjectOptions): ProjectRulesResult {
  const home = options?.homeDir || getHomeDir();
  const hub = options?.hubDir || getHubDir();

  const rulesRes = projectRules(options);
  const subagentsRes = projectSubagents(home, hub);

  return {
    success: rulesRes.success && subagentsRes.success,
    messages: [...rulesRes.messages, ...subagentsRes.results],
  };
}
