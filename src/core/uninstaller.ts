/**
 * Uninstaller and rollback engine for agenthub.
 * Safely restores pre-agenthub configuration backups, unlinks skills junctions,
 * restores original skills folders, and cleans up generated rules.
 */

import fs from 'node:fs';
import path from 'node:path';
import { createJunction, ensureDir } from '../utils/fs.js';
import { getHomeDir, getHubDir } from './detector.js';
import { MCP_PLATFORMS, MCP_PLATFORM_IDS, readPlatform, removePlatformServers, type McpPlatformId, type PlatformState } from './mcp-platforms.js';
import { expandServerPaths, platformDrifted, readJsonSafely, readOrigins, type McpServerConfig } from './mcp-sync.js';

export interface UninstallOptions {
  home?: string;
  hub?: string;
  dryRun?: boolean;
  purge?: boolean;
}

export interface UninstallResult {
  success: boolean;
  backupRestored: string | null;
  restoredFiles: string[];
  unlinkedJunctions: string[];
  restoredJunctions: string[];
  removedFiles: string[];
  /** MCP entries removed from platform configs that no backup restored, as "<platform>:<server>" */
  removedMcpServers: string[];
  /** "<platform>:<server> (reason)" for servers left in place */
  keptMcpServers: string[];
  purgedHub: boolean;
  errors: string[];
}

/**
 * Looks in path.join(hubDir, 'backups') for directories starting with 'pre-agenthub-'.
 * Sorts alphabetically and returns the first one (or null if none).
 */
export function findEarliestBackup(hubDir: string): string | null {
  const backupsDir = path.join(hubDir, 'backups');
  if (!fs.existsSync(backupsDir)) {
    return null;
  }

  try {
    const entries = fs.readdirSync(backupsDir, { withFileTypes: true });
    const matching = entries
      .filter((entry) => entry.isDirectory() && entry.name.startsWith('pre-agenthub-'))
      .map((entry) => entry.name)
      .sort((a, b) => a.localeCompare(b));

    if (matching.length === 0) {
      return null;
    }

    return path.join(backupsDir, matching[0]);
  } catch {
    return null;
  }
}

/**
 * Determines whether the given text content belongs to an agenthub
 * autogenerated configuration file.
 */
export function isAgenthubContent(content: string | null): boolean {
  if (!content) return false;
  const lower = content.toLowerCase();
  return (
    lower.includes('agenthub') ||
    lower.includes('autogenerated by agenthub')
  );
}

/**
 * Recursively walks backupDir and copies every file back to path.join(homeDir, relativePath).
 * Creates parent directories as needed.
 */
export function restoreFromBackup(
  backupDir: string,
  homeDir: string,
  dryRun?: boolean
): string[] {
  const restored: string[] = [];
  if (!fs.existsSync(backupDir)) {
    return restored;
  }

  const resolvedHome = path.resolve(homeDir);
  const homePrefix = resolvedHome.endsWith(path.sep) ? resolvedHome : resolvedHome + path.sep;

  function walk(current: string): void {
    const entries = fs.readdirSync(current, { withFileTypes: true });
    for (const entry of entries) {
      const fullPath = path.join(current, entry.name);
      if (entry.isDirectory()) {
        walk(fullPath);
      } else if (entry.isFile()) {
        const rel = path.relative(backupDir, fullPath);
        const relPosix = rel.replace(/\\/g, '/');
        const dest = path.resolve(homeDir, rel);

        const isInside =
          process.platform === 'win32'
            ? dest.toLowerCase().startsWith(homePrefix.toLowerCase())
            : dest.startsWith(homePrefix);

        if (!isInside) {
          throw new Error(
            `Path traversal detected in backup: "${rel}" resolves outside target home`
          );
        }

        if (!dryRun) {
          ensureDir(path.dirname(dest));
          fs.copyFileSync(fullPath, dest);
        }

        restored.push(relPosix);
      }
    }
  }

  walk(backupDir);
  return restored;
}

function isMatchingHubTarget(linkPath: string, hubDir: string): boolean {
  let rawTarget: string | null = null;
  try {
    rawTarget = fs.readlinkSync(linkPath);
  } catch {
    // ignore
  }

  let realTarget: string | null = null;
  try {
    realTarget = fs.realpathSync(linkPath);
  } catch {
    // ignore
  }

  const hubSkillsNorm = path
    .resolve(hubDir, 'skills')
    .toLowerCase()
    .replace(/\\/g, '/')
    .replace(/^\\\\\?\\/, '');

  const targetsToCheck = [rawTarget, realTarget].filter(Boolean) as string[];
  for (const t of targetsToCheck) {
    const norm = t
      .toLowerCase()
      .replace(/\\/g, '/')
      .replace(/^\\\\\?\\/, '');

    if (norm === hubSkillsNorm) return true;
    if (norm.endsWith('/.agenthub/skills') || norm === '.agenthub/skills') return true;
    if (norm.endsWith('/' + path.basename(hubDir).toLowerCase() + '/skills')) return true;

    try {
      const resolved = path
        .resolve(path.dirname(linkPath), t)
        .toLowerCase()
        .replace(/\\/g, '/')
        .replace(/^\\\\\?\\/, '');
      if (resolved === hubSkillsNorm) return true;
      if (resolved.endsWith('/.agenthub/skills')) return true;
    } catch {
      // ignore
    }
  }

  return false;
}

/**
 * Checks .claude/skills, .codex/skills, .cursor/skills, .codeium/windsurf/skills, .windsurf/skills, .copilot/skills.
 * If it is a symlink/junction pointing to hubDir/skills or includes .agenthub:
 * Unlinks the junction.
 * If skills.old exists in parent directory, renames skills.old -> skills.
 */
export function cleanupJunctions(
  homeDir: string,
  hubDir: string,
  dryRun?: boolean
): { unlinked: string[]; restored: string[] } {
  const unlinked: string[] = [];
  const restored: string[] = [];

  const candidateLinks = [
    path.join(homeDir, '.claude', 'skills'),
    path.join(homeDir, '.codex', 'skills'),
    path.join(homeDir, '.cursor', 'skills'),
    path.join(homeDir, '.codeium', 'windsurf', 'skills'),
    path.join(homeDir, '.windsurf', 'skills'),
    path.join(homeDir, '.copilot', 'skills'),
  ];

  for (const linkPath of candidateLinks) {
    let isLink = false;
    try {
      const stat = fs.lstatSync(linkPath);
      isLink = stat.isSymbolicLink();
    } catch {
      isLink = false;
    }

    if (!isLink) {
      // Cursor's link is removed on purpose while Claude or Codex provide the skills: bring its old folder back
      const old = path.join(path.dirname(linkPath), 'skills.old');
      if (linkPath.includes(`${path.sep}.cursor${path.sep}`) && !fs.existsSync(linkPath) && fs.existsSync(old)) {
        if (!dryRun) fs.renameSync(old, linkPath);
        restored.push(linkPath);
      }
      continue;
    }

    if (!isMatchingHubTarget(linkPath, hubDir)) {
      continue;
    }

    unlinked.push(linkPath);

    if (!dryRun) {
      try {
        fs.unlinkSync(linkPath);
      } catch {
        try {
          fs.rmdirSync(linkPath);
        } catch {
          fs.rmSync(linkPath, { recursive: true, force: true });
        }
      }
    }

    const parentDir = path.dirname(linkPath);
    const skillsOld = path.join(parentDir, 'skills.old');

    if (fs.existsSync(skillsOld)) {
      if (!dryRun) {
        fs.renameSync(skillsOld, linkPath);
      }
      restored.push(linkPath);
    }
  }

  return { unlinked, restored };
}

/**
 * Cleans up generated rules and subagents that were not restored from backup.
 */
export function cleanupGeneratedRules(
  homeDir: string,
  hubDir: string,
  restoredFiles: Set<string>,
  dryRun?: boolean
): string[] {
  const removed: string[] = [];

  function isRestored(filePath: string): boolean {
    const rel = path.relative(homeDir, filePath);
    const relPosix = rel.replace(/\\/g, '/');
    const relWin = rel.replace(/\//g, '\\');
    const absPath = path.resolve(filePath);

    return (
      restoredFiles.has(filePath) ||
      restoredFiles.has(absPath) ||
      restoredFiles.has(rel) ||
      restoredFiles.has(relPosix) ||
      restoredFiles.has(relWin)
    );
  }

  function readContentSafely(filePath: string): string | null {
    try {
      return fs.readFileSync(filePath, 'utf-8');
    } catch {
      return null;
    }
  }

  function checkFileRemoval(filePath: string, condition: () => boolean): void {
    if (!fs.existsSync(filePath)) {
      return;
    }
    try {
      const stat = fs.statSync(filePath);
      if (!stat.isFile()) return;
    } catch {
      return;
    }

    if (isRestored(filePath)) {
      return;
    }

    if (condition()) {
      removed.push(filePath);
      if (!dryRun) {
        try {
          fs.unlinkSync(filePath);
        } catch {
          // ignore unlink error
        }
      }
    }
  }

  // 1. path.join(homeDir, '.cursor', 'rules', 'agenthub.mdc')
  const cursorMdcHub = path.join(homeDir, '.cursor', 'rules', 'agenthub.mdc');
  checkFileRemoval(cursorMdcHub, () => true);
  const cursorMdcRc = path.join(homeDir, '.cursor', 'rules', 'agentrc.mdc');
  checkFileRemoval(cursorMdcRc, () => true);

  // 2. path.join(homeDir, '.cursorrules'): if exists and not in restoredFiles and file content includes agenthub, remove
  const cursorrules = path.join(homeDir, '.cursorrules');
  checkFileRemoval(cursorrules, () => isAgenthubContent(readContentSafely(cursorrules)));

  // 3. path.join(homeDir, '.windsurfrules'): if exists and not in restoredFiles and file content includes agenthub, remove
  const windsurfrules = path.join(homeDir, '.windsurfrules');
  checkFileRemoval(windsurfrules, () => isAgenthubContent(readContentSafely(windsurfrules)));

  // 4. path.join(homeDir, '.windsurf', 'memories', 'global_rules.md')
  const windsurfGlobalRules = path.join(homeDir, '.windsurf', 'memories', 'global_rules.md');
  checkFileRemoval(windsurfGlobalRules, () => isAgenthubContent(readContentSafely(windsurfGlobalRules)));

  // 5. path.join(homeDir, '.codeium', 'windsurf', 'memories', 'global_rules.md')
  const codeiumGlobalRules = path.join(homeDir, '.codeium', 'windsurf', 'memories', 'global_rules.md');
  checkFileRemoval(codeiumGlobalRules, () => isAgenthubContent(readContentSafely(codeiumGlobalRules)));

  // 6. path.join(homeDir, '.gemini', 'GEMINI.md') and path.join(homeDir, '.gemini', 'config', 'GEMINI.md')
  const geminiRules = path.join(homeDir, '.gemini', 'GEMINI.md');
  checkFileRemoval(geminiRules, () => isAgenthubContent(readContentSafely(geminiRules)));
  const geminiConfigRules = path.join(homeDir, '.gemini', 'config', 'GEMINI.md');
  checkFileRemoval(geminiConfigRules, () => isAgenthubContent(readContentSafely(geminiConfigRules)));

  // If pre-agenthub .gemini/config/GEMINI.md.backup or .gemini/GEMINI.md.backup exists, restore it back to GEMINI.md
  const geminiBackups = [
    {
      backup: path.join(homeDir, '.gemini', 'config', 'GEMINI.md.backup'),
      dest: path.join(homeDir, '.gemini', 'config', 'GEMINI.md'),
    },
    {
      backup: path.join(homeDir, '.gemini', 'GEMINI.md.backup'),
      dest: path.join(homeDir, '.gemini', 'GEMINI.md'),
    },
  ];

  for (const { backup, dest } of geminiBackups) {
    if (fs.existsSync(backup)) {
      if (!dryRun) {
        try {
          if (fs.existsSync(dest)) {
            fs.unlinkSync(dest);
          }
          ensureDir(path.dirname(dest));
          fs.renameSync(backup, dest);
        } catch {
          // ignore error
        }
      }
    }
  }

  // 7. path.join(homeDir, '.claude', 'CLAUDE.md'): if exists and not in restoredFiles and file content includes agenthub, remove
  const claudeRules = path.join(homeDir, '.claude', 'CLAUDE.md');
  checkFileRemoval(claudeRules, () => isAgenthubContent(readContentSafely(claudeRules)));

  // 8. path.join(homeDir, '.codex', 'AGENTS.md'): if exists and not in restoredFiles and file content includes agenthub, remove
  const codexRules = path.join(homeDir, '.codex', 'AGENTS.md');
  checkFileRemoval(codexRules, () => isAgenthubContent(readContentSafely(codexRules)));

  // 9. In .claude/agents/*.md and .gemini/config/agents/*.md:
  // if not in restoredFiles, if file contains 'agenthub' or was projected from hubDir/agents/ (including scout.md/implementer.md/reviewer.md), remove
  const agentDirs = [
    path.join(homeDir, '.claude', 'agents'),
    path.join(homeDir, '.gemini', 'config', 'agents'),
  ];

  const projectedAgentNames = new Set(['scout.md', 'implementer.md', 'reviewer.md']);
  const hubAgentsDir = path.join(hubDir, 'agents');
  if (fs.existsSync(hubAgentsDir)) {
    try {
      const hubEntries = fs.readdirSync(hubAgentsDir, { withFileTypes: true });
      for (const entry of hubEntries) {
        if (entry.isFile() && entry.name.endsWith('.md')) {
          projectedAgentNames.add(entry.name.toLowerCase());
        }
      }
    } catch {
      // ignore readdir error
    }
  }

  for (const agentDir of agentDirs) {
    if (!fs.existsSync(agentDir)) continue;
    try {
      const entries = fs.readdirSync(agentDir, { withFileTypes: true });
      for (const entry of entries) {
        if (!entry.isFile() || !entry.name.endsWith('.md')) continue;
        const agentFile = path.join(agentDir, entry.name);
        if (isRestored(agentFile)) continue;

        const isProjected = projectedAgentNames.has(entry.name.toLowerCase());
        const content = readContentSafely(agentFile);
        const hasAgenthub = isAgenthubContent(content);

        if (isProjected || hasAgenthub) {
          removed.push(agentFile);
          if (!dryRun) {
            try {
              fs.unlinkSync(agentFile);
            } catch {
              // ignore
            }
          }
        }
      }
    } catch {
      // ignore readdir error
    }
  }

  return removed;
}

/**
 * Removes servers the hub itself wrote into Codex, Cursor, Windsurf and Copilot
 * configs that no backup restored. A server stays when it was ingested from that
 * platform (it was there before agenthub), when it was never recorded as written
 * there, or when the user changed it since. With purge, a server that would exist
 * nowhere else after the hub is deleted stays too. Each file is read once.
 */
export function cleanupMcpEntries(
  homeDir: string,
  hubDir: string,
  restoredFiles: Set<string>,
  dryRun?: boolean,
  purge?: boolean
): { removed: string[]; kept: string[] } {
  const removed: string[] = [];
  const kept: string[] = [];
  const read = readJsonSafely<{ mcpServers?: Record<string, McpServerConfig> }>(path.join(hubDir, 'mcp', 'servers.json'));
  const hubServers = read.success && read.data.mcpServers && typeof read.data.mcpServers === 'object' ? read.data.mcpServers : {};
  if (Object.keys(hubServers).length === 0) return { removed, kept };
  const expanded = Object.fromEntries(Object.entries(hubServers).map(([n, c]) => [n, expandServerPaths(c, homeDir, hubDir)]));
  const origins = readOrigins(hubDir);

  const plan: Array<{ id: McpPlatformId; state: PlatformState; names: string[] }> = [];
  for (const id of MCP_PLATFORM_IDS) {
    const platform = MCP_PLATFORMS[id];
    if (platform.legacy) continue;
    const state = readPlatform(platform, homeDir);
    const restored = state.files.every((f) => restoredFiles.has(path.relative(homeDir, f.path).replace(/\\/g, '/')) || restoredFiles.has(f.path));
    if (restored || !state.valid) continue;
    const names: string[] = [];
    for (const name of Object.keys(expanded)) {
      const native = state.servers[name];
      if (!native) continue;
      const o = origins[name];
      if (o?.from.includes(id)) kept.push(`${id}:${name} (it was there before agenthub)`);
      else if (!o?.to.includes(id)) kept.push(`${id}:${name} (not written by agenthub)`);
      else if (platformDrifted(platform, native, expanded[name])) kept.push(`${id}:${name} (changed since)`);
      else names.push(name);
    }
    plan.push({ id, state, names });
  }

  if (purge) {
    // after a purge only these remain: Claude/Gemini configs and the entries kept above
    const survives = new Set<string>();
    for (const id of ['claude', 'gemini'] as const) Object.keys(readPlatform(MCP_PLATFORMS[id], homeDir).servers).forEach((n) => survives.add(n));
    for (const p of plan) for (const name of Object.keys(p.state.servers)) if (!p.names.includes(name)) survives.add(name);
    for (const p of plan) {
      p.names = p.names.filter((name) => {
        if (survives.has(name)) return true;
        kept.push(`${p.id}:${name} (the only copy once the hub is purged)`);
        survives.add(name);
        return false;
      });
    }
  }

  for (const p of plan) {
    if (p.names.length === 0) continue;
    if (!dryRun) removePlatformServers(MCP_PLATFORMS[p.id], p.state, p.names);
    removed.push(...p.names.map((n) => `${p.id}:${n}`));
  }
  return { removed, kept };
}

/**
 * Orchestrates full uninstallation and rollback of agenthub.
 */
export function uninstallHub(options?: UninstallOptions): UninstallResult {
  const homeDir = options?.home || getHomeDir();
  const hubDir = options?.hub || getHubDir();
  const dryRun = Boolean(options?.dryRun);
  const purge = Boolean(options?.purge);

  const resolvedHome = path.resolve(homeDir);
  const resolvedHub = path.resolve(hubDir);
  const rootDir = path.parse(resolvedHub).root;

  const isHomeOrRoot =
    process.platform === 'win32'
      ? resolvedHub.toLowerCase() === resolvedHome.toLowerCase() ||
        resolvedHub.toLowerCase() === rootDir.toLowerCase()
      : resolvedHub === resolvedHome || resolvedHub === rootDir;

  if (purge && isHomeOrRoot) {
    throw new Error(
      `Refusing to purge hub directory: "${hubDir}" is home directory or filesystem root.`
    );
  }

  const errors: string[] = [];

  // 1. Find earliest backup
  const earliestBackup = findEarliestBackup(hubDir);

  // 2. Restore backed up files
  let restoredFiles: string[] = [];
  if (earliestBackup) {
    try {
      restoredFiles = restoreFromBackup(earliestBackup, homeDir, dryRun);
    } catch (err) {
      errors.push(`Failed to restore from backup: ${(err as Error).message}`);
    }
  }

  const restoredFilesSet = new Set<string>();
  for (const f of restoredFiles) {
    restoredFilesSet.add(f);
    restoredFilesSet.add(f.replace(/\\/g, '/'));
    restoredFilesSet.add(path.resolve(homeDir, f));
  }

  // 3. Clean up junctions and restore skills.old
  let unlinkedJunctions: string[] = [];
  let restoredJunctions: string[] = [];
  try {
    const junctionRes = cleanupJunctions(homeDir, hubDir, dryRun);
    unlinkedJunctions = junctionRes.unlinked;
    restoredJunctions = junctionRes.restored;
  } catch (err) {
    errors.push(`Failed to clean up junctions: ${(err as Error).message}`);
  }

  // 4. Clean up leftover generated rules and agents not in backup
  let removedFiles: string[] = [];
  try {
    removedFiles = cleanupGeneratedRules(homeDir, hubDir, restoredFilesSet, dryRun);
  } catch (err) {
    errors.push(`Failed to clean up generated rules: ${(err as Error).message}`);
  }

  // 5. Remove hub MCP entries from platform configs that were not restored
  let removedMcpServers: string[] = [];
  let keptMcpServers: string[] = [];
  try {
    ({ removed: removedMcpServers, kept: keptMcpServers } = cleanupMcpEntries(homeDir, hubDir, restoredFilesSet, dryRun, purge));
  } catch (err) {
    errors.push(`Failed to clean up MCP entries: ${(err as Error).message}`);
  }

  // 6. Purge hub directory if requested
  let purgedHub = false;
  if (purge) {
    if (!dryRun) {
      try {
        if (fs.existsSync(hubDir)) {
          fs.rmSync(hubDir, { recursive: true, force: true });
        }
        purgedHub = true;
      } catch (err) {
        errors.push(`Failed to purge hub directory: ${(err as Error).message}`);
      }
    } else {
      purgedHub = true;
    }
  }

  return {
    success: errors.length === 0,
    backupRestored: earliestBackup,
    restoredFiles,
    unlinkedJunctions,
    restoredJunctions,
    removedFiles,
    removedMcpServers,
    keptMcpServers,
    purgedHub,
    errors,
  };
}
