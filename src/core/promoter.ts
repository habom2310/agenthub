/**
 * Rule promoter and drift detector for agenthub.
 * Compares downstream assistant configurations against hub rules,
 * detects drifts and modified chunks, and promotes rule chunks upstream.
 */

import fs from 'node:fs';
import path from 'node:path';
import { ensureDir, safeWriteFile } from '../utils/fs.js';
import { ChunkDiff, MarkdownChunk, computeNormalizedHash, diffChunks, parseMarkdownChunks } from './chunker.js';
import { getHomeDir, getHubDir } from './detector.js';
import {
  HEADER_GUARD,
  PLATFORM_RULE_FILES,
  projectClaudeRules,
  projectCodexRules,
  projectCursorRules,
  projectGeminiRules,
  projectWindsurfRules,
} from './projector.js';

export interface PlatformDriftReport {
  file: string;
  exists: boolean;
  hasDrift: boolean;
  added: MarkdownChunk[];
  modified: Array<{ source: MarkdownChunk; target: MarkdownChunk }>;
  removed: MarkdownChunk[];
  identical: MarkdownChunk[];
}

export type PlatformDriftTarget = 'gemini' | 'claude' | 'codex';
export type RuleDriftAudit = Record<PlatformDriftTarget, PlatformDriftReport>;

export interface PromoteOptions {
  targetRuleFile?: string; // defaults to "common.md"
  hubDir?: string;
  homeDir?: string;
  reproject?: boolean;     // defaults to true
}

export interface PromoteResult {
  success: boolean;
  message: string;
}

/**
 * Generates expected concatenated rules text for a platform from rules in rulesDir.
 */
export function getExpectedRulesText(platform: string, rulesDir: string): string {
  const parts: string[] = [HEADER_GUARD.trim()];
  const fileList = PLATFORM_RULE_FILES[platform] || ['common.md', 'code-tools.md', 'handoffs.md'];
  for (const fileName of fileList) {
    const filePath = path.join(rulesDir, fileName);
    if (fs.existsSync(filePath) && fs.statSync(filePath).isFile()) {
      const content = fs.readFileSync(filePath, 'utf-8').trim();
      if (content) {
        parts.push(content);
      }
    }
  }
  return parts.join('\n\n') + '\n';
}

/**
 * Detects rule drift across platform rule files compared against expected hub rules.
 */
export function detectRuleDrift(homeDir?: string, hubDir?: string): RuleDriftAudit {
  const home = homeDir || getHomeDir();
  const hub = hubDir || getHubDir();
  const rulesDir = path.resolve(hub, 'rules');

  const targets: Record<PlatformDriftTarget, string> = {
    gemini: path.join(home, '.gemini', 'GEMINI.md'),
    claude: path.join(home, '.claude', 'CLAUDE.md'),
    codex: path.join(home, '.codex', 'AGENTS.md'),
  };

  const audit = {} as RuleDriftAudit;

  for (const [platform, filePath] of Object.entries(targets) as Array<[PlatformDriftTarget, string]>) {
    if (!fs.existsSync(filePath) || !fs.statSync(filePath).isFile()) {
      audit[platform] = {
        file: filePath,
        exists: false,
        hasDrift: false,
        added: [],
        modified: [],
        removed: [],
        identical: [],
      };
      continue;
    }

    const rawDownstream = fs.readFileSync(filePath, 'utf-8');
    const isImportManifest =
      platform === 'claude' &&
      rawDownstream
        .split(/\r?\n/)
        .some((line) => {
          const norm = line.replace(/\\/g, '/').trim();
          return norm.startsWith('@') && (norm.includes('rules/') || norm.includes('common.md'));
        });

    let diff: ChunkDiff;
    if (isImportManifest) {
      const lines = rawDownstream.split(/\r?\n/);
      const unimportedLines = lines.filter((line) => {
        const trimmed = line.trim();
        if (trimmed.startsWith('@')) return false;
        if (line.includes('AUTOGENERATED BY AGENTRC') || line.includes('AUTOGENERATED BY AGENTHUB')) {
          return false;
        }
        return true;
      });
      const unimportedText = unimportedLines.join('\n').trim();
      const downstreamChunks = unimportedText ? parseMarkdownChunks(unimportedText) : [];
      diff = diffChunks(downstreamChunks, []);

      // Check if all expected @import rules are present
      const normalizedLines = lines.map((line) => line.replace(/\\/g, '/').trim());
      const importLines = normalizedLines.filter((line) => line.startsWith('@'));
      const existingRuleFiles = PLATFORM_RULE_FILES.claude.filter((f) =>
        fs.existsSync(path.join(rulesDir, f))
      );
      for (const file of existingRuleFiles) {
        const normFile = file.replace(/\\/g, '/');
        const hasImport = importLines.some((line) => line.includes(normFile));
        if (!hasImport) {
          diff.removed.push({
            header: `@import ${file}`,
            level: 0,
            path: [`@import ${file}`],
            content: `@${file}`,
            raw: `@${file}\n`,
            normalizedHash: computeNormalizedHash(`@${file}`),
            codeBlocks: [],
          });
        }
      }
    } else {
      const expectedText = getExpectedRulesText(platform, rulesDir);
      const expectedChunks = parseMarkdownChunks(expectedText);
      const downstreamChunks = parseMarkdownChunks(rawDownstream);
      diff = diffChunks(downstreamChunks, expectedChunks);
    }

    const hasDrift = diff.added.length > 0 || diff.modified.length > 0 || diff.removed.length > 0;

    audit[platform] = {
      file: filePath,
      exists: true,
      hasDrift,
      added: diff.added,
      modified: diff.modified,
      removed: diff.removed,
      identical: diff.identical,
    };
  }

  return audit;
}

/**
 * Promotes a markdown chunk upstream into hub rules, handling in-place modification,
 * hierarchical child insertion, or root section appending, with optional re-projection.
 */
export function promoteChunk(chunk: MarkdownChunk, options?: PromoteOptions): PromoteResult {
  let targetRuleFile = options?.targetRuleFile || 'common.md';
  if (!targetRuleFile.endsWith('.md')) {
    targetRuleFile = `${targetRuleFile}.md`;
  }

  const hubDir = options?.hubDir || getHubDir();
  const homeDir = options?.homeDir || getHomeDir();
  const reproject = options?.reproject !== false;

  const rulesDir = path.resolve(hubDir, 'rules');
  ensureDir(rulesDir);

  const targetPath = path.resolve(rulesDir, targetRuleFile);

  const rel = path.relative(rulesDir, targetPath);
  if (rel.startsWith('..') || path.isAbsolute(rel)) {
    return {
      success: false,
      message: `Target file must reside inside hub rules directory: ${targetRuleFile}`,
    };
  }

  let newText: string;

  if (fs.existsSync(targetPath) && fs.statSync(targetPath).isFile()) {
    const existingText = fs.readFileSync(targetPath, 'utf-8').replace(/\r\n/g, '\n').replace(/\r/g, '\n');
    const existingChunks = parseMarkdownChunks(existingText);

    // 1. Check for in-place modification (existing chunk with exact same path)
    const targetChunk = existingChunks.find(
      (c) => c.path.length === chunk.path.length && c.path.every((p, i) => p === chunk.path[i])
    );

    if (targetChunk && existingText.includes(targetChunk.raw)) {
      newText = existingText.replace(targetChunk.raw, () => chunk.raw.trimEnd() + '\n');
    } else if (chunk.path.length > 1) {
      const parentPath = chunk.path.slice(0, -1);
      const parentChunkIndex = existingChunks.findIndex(
        (c) => c.path.length === parentPath.length && c.path.every((p, i) => p === parentPath[i])
      );

      if (parentChunkIndex !== -1) {
        const parentChunk = existingChunks[parentChunkIndex];
        let lastDescendant = parentChunk;
        for (let i = parentChunkIndex + 1; i < existingChunks.length; i++) {
          const candidate = existingChunks[i];
          if (candidate.level > parentChunk.level) {
            lastDescendant = candidate;
          } else {
            break;
          }
        }
        const targetRaw = lastDescendant.raw;
        newText = existingText.replace(
          targetRaw,
          () => targetRaw.trimEnd() + '\n\n' + chunk.raw.trim() + '\n'
        );
      } else {
        newText = existingText.trimEnd() + '\n\n' + chunk.raw.trim() + '\n';
      }
    } else {
      newText = existingText.trimEnd() + '\n\n' + chunk.raw.trim() + '\n';
    }
  } else {
    newText = chunk.raw.trim() + '\n';
  }

  safeWriteFile(targetPath, newText);

  if (reproject) {
    projectGeminiRules(homeDir, hubDir);
    projectClaudeRules({ homeDir, hubDir });
    projectCodexRules(homeDir, hubDir);
    projectCursorRules(undefined, homeDir, hubDir);
    projectWindsurfRules(undefined, homeDir, hubDir);
  }

  return {
    success: true,
    message: `Promoted rule '${chunk.header}' into ${targetRuleFile}`,
  };
}
