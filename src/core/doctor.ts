import fs from 'node:fs';
import path from 'node:path';
import { connectCursor, connectWindsurf } from './connector.js';
import { getHomeDir, getHubDir, skillPlatform } from './detector.js';
import {
  cursorSkillsProvider,
  isLinkTo,
  linkSkillsForClaude,
  linkSkillsForCodex,
  linkSkillsForCopilot,
  linkSkillsForGemini,
  projectCodexSkillManifests,
} from './linker.js';
import { MCP_PLATFORMS, MCP_PLATFORM_IDS } from './mcp-platforms.js';
import { getMcpStatus, syncMcpServers } from './mcp-sync.js';
import {
  projectClaudeRules,
  projectCodexRules,
  projectGeminiRules,
  projectSubagents,
} from './projector.js';

export interface DoctorOptions {
  fix?: boolean;
  homeDir?: string;
  hubDir?: string;
}

export interface DoctorResult {
  status: 'PASS' | 'WARN';
  passed_checks: string[];
  issues: string[];
  repairs: string[];
}

function performChecks(
  homeDir: string,
  hubDir: string
): { passed_checks: string[]; issues: string[] } {
  const passed_checks: string[] = [];
  const issues: string[] = [];

  const hubSkills = path.join(hubDir, 'skills');

  // Check 1: Hub manifest
  const agenthubJson = path.join(hubDir, 'agenthub.json');
  let manifestData: any = null;

  if (fs.existsSync(agenthubJson)) {
    try {
      manifestData = JSON.parse(fs.readFileSync(agenthubJson, 'utf-8'));
      passed_checks.push('Hub manifest exists');
    } catch {
      issues.push(`Hub manifest ${agenthubJson} is invalid JSON`);
    }
  } else {
    issues.push(`Hub manifest missing: agenthub.json not found in ${hubDir}`);
  }

  // Check 2: Claude skills junction
  const claudeSkills = path.join(homeDir, '.claude', 'skills');
  if (isLinkTo(claudeSkills, hubSkills)) {
    passed_checks.push('Claude skills junction verified');
  } else {
    issues.push(`Claude skills junction missing or invalid: ${claudeSkills} does not resolve to ${hubSkills}`);
  }

  // Check 3: Antigravity skills JSON
  const geminiSkillsJson = path.join(homeDir, '.gemini', 'config', 'skills.json');
  if (fs.existsSync(geminiSkillsJson)) {
    try {
      const data = JSON.parse(fs.readFileSync(geminiSkillsJson, 'utf-8'));
      const entries = Array.isArray(data?.entries) ? data.entries : [];
      const hubSkillsResolved = path.resolve(hubSkills).toLowerCase();
      let found = false;
      for (const entry of entries) {
        const p = String(entry?.path || '');
        if (
          path.resolve(p).toLowerCase() === hubSkillsResolved ||
          p.toLowerCase() === hubSkillsResolved.replace(/\\/g, '/') ||
          p.includes('.agenthub') ||
          p.includes('agenthub')
        ) {
          found = true;
          break;
        }
      }
      if (found) {
        passed_checks.push('Antigravity skills configuration verified');
      } else {
        issues.push(`Antigravity skills configuration does not reference hub skills: ${geminiSkillsJson}`);
      }
    } catch {
      issues.push(`Antigravity skills configuration is invalid JSON: ${geminiSkillsJson}`);
    }
  } else {
    issues.push(`Antigravity skills configuration missing: ${geminiSkillsJson}`);
  }

  // Check 4: Gemini rules
  const geminiRules = path.join(homeDir, '.gemini', 'GEMINI.md');
  if (fs.existsSync(geminiRules)) {
    try {
      const content = fs.readFileSync(geminiRules, 'utf-8');
      if (content.includes('AUTOGENERATED BY AGENTHUB')) {
        passed_checks.push('Gemini rules verified');
      } else {
        issues.push(`Gemini rules missing header guard: ${geminiRules}`);
      }
    } catch (err) {
      issues.push(`Failed to read Gemini rules: ${(err as Error).message}`);
    }
  } else {
    issues.push(`Gemini rules file missing: ${geminiRules}`);
  }

  // Check 5: Claude rules
  const claudeRules = path.join(homeDir, '.claude', 'CLAUDE.md');
  if (fs.existsSync(claudeRules)) {
    try {
      const content = fs.readFileSync(claudeRules, 'utf-8');
      if (
        content.includes('@') ||
        content.includes('AUTOGENERATED BY AGENTHUB')
      ) {
        passed_checks.push('Claude rules verified');
      } else {
        issues.push(`Claude rules missing header guard or @ import: ${claudeRules}`);
      }
    } catch (err) {
      issues.push(`Failed to read Claude rules: ${(err as Error).message}`);
    }
  } else {
    issues.push(`Claude rules file missing: ${claudeRules}`);
  }

  // Check 6, 7, 8: Codex checks (if home/.codex exists)
  const codexDir = path.join(homeDir, '.codex');
  if (fs.existsSync(codexDir) && fs.statSync(codexDir).isDirectory()) {
    // Check 6: Codex rules
    const codexRules = path.join(codexDir, 'AGENTS.md');
    if (fs.existsSync(codexRules)) {
      try {
        const content = fs.readFileSync(codexRules, 'utf-8');
        if (content.includes('AUTOGENERATED BY AGENTHUB')) {
          passed_checks.push('Codex rules verified');
        } else {
          issues.push(`Codex rules missing header guard: ${codexRules}`);
        }
      } catch (err) {
        issues.push(`Failed to read Codex rules: ${(err as Error).message}`);
      }
    } else {
      issues.push(`Codex rules file missing: ${codexRules}`);
    }

    // Check 7: Codex skills junction
    const codexSkills = path.join(codexDir, 'skills');
    if (isLinkTo(codexSkills, hubSkills)) {
      passed_checks.push('Codex skills junction verified');
    } else {
      issues.push(`Codex skills junction missing or invalid: ${codexSkills} does not resolve to ${hubSkills}`);
    }

    // Check 8: Codex skill manifests
    const skillsDir = path.join(hubDir, 'skills');
    if (fs.existsSync(skillsDir) && fs.statSync(skillsDir).isDirectory()) {
      const missingManifests: string[] = [];
      const entries = fs.readdirSync(skillsDir);
      for (const entry of entries) {
        const skillPath = path.join(skillsDir, entry);
        try {
          if (
            fs.statSync(skillPath).isDirectory() &&
            fs.existsSync(path.join(skillPath, 'SKILL.md'))
          ) {
            const manifestPath = path.join(skillPath, 'agents', 'openai.yaml');
            if (!fs.existsSync(manifestPath)) {
              missingManifests.push(entry);
            }
          }
        } catch {
          // ignore error
        }
      }
      if (missingManifests.length === 0) {
        passed_checks.push('Codex skill manifests verified');
      } else {
        issues.push(`Codex skill manifest missing: agents/openai.yaml not found for skill(s): ${missingManifests.join(', ')}`);
      }
    } else {
      passed_checks.push('Codex skill manifests verified (no hub skills)');
    }
  }

  // Check 9, 10: Cursor checks (if enabled or detected)
  const cursorDir =
    (manifestData?.platforms?.cursor?.path as string) ||
    path.join(homeDir, '.cursor');
  const cursorEnabled = manifestData?.platforms?.cursor?.enabled === true;
  const cursorRulesLegacy = path.join(homeDir, '.cursorrules');
  const cursorDetected =
    cursorEnabled ||
    (fs.existsSync(cursorDir) && fs.statSync(cursorDir).isDirectory()) ||
    (fs.existsSync(cursorRulesLegacy) && fs.statSync(cursorRulesLegacy).isFile());

  if (cursorDetected) {
    // Check 9: Cursor skills junction
    const cursorSkills = path.join(cursorDir, 'skills');
    const provider = cursorSkillsProvider(homeDir, hubDir);
    if (isLinkTo(cursorSkills, hubSkills)) {
      passed_checks.push('Cursor skills junction verified');
    } else if (provider) {
      passed_checks.push(`Cursor skills provided through ${provider}`);
    } else {
      issues.push(`Cursor skills junction missing or invalid: ${cursorSkills} does not resolve to ${hubSkills}`);
    }

    // Check 10: Cursor rules
    const mdcHub = path.join(cursorDir, 'rules', 'agenthub.mdc');
    if (
      (fs.existsSync(mdcHub) && fs.statSync(mdcHub).isFile()) ||
      (fs.existsSync(cursorRulesLegacy) && fs.statSync(cursorRulesLegacy).isFile())
    ) {
      passed_checks.push('Cursor rules verified');
    } else {
      issues.push(`Cursor rules missing: expected ${mdcHub} or ${cursorRulesLegacy}`);
    }
  }

  // Check 11, 12: Windsurf checks (if enabled or detected)
  let windsurfDir = manifestData?.platforms?.windsurf?.path as string;
  if (!windsurfDir) {
    const codeiumDir = path.join(homeDir, '.codeium', 'windsurf');
    windsurfDir =
      fs.existsSync(codeiumDir) && fs.statSync(codeiumDir).isDirectory()
        ? codeiumDir
        : path.join(homeDir, '.windsurf');
  }
  const windsurfEnabled = manifestData?.platforms?.windsurf?.enabled === true;
  const windsurfRulesLegacy = path.join(homeDir, '.windsurfrules');
  const windsurfDetected =
    windsurfEnabled ||
    (fs.existsSync(windsurfDir) && fs.statSync(windsurfDir).isDirectory()) ||
    (fs.existsSync(path.join(homeDir, '.codeium', 'windsurf')) &&
      fs.statSync(path.join(homeDir, '.codeium', 'windsurf')).isDirectory()) ||
    (fs.existsSync(path.join(homeDir, '.windsurf')) &&
      fs.statSync(path.join(homeDir, '.windsurf')).isDirectory()) ||
    (fs.existsSync(windsurfRulesLegacy) && fs.statSync(windsurfRulesLegacy).isFile());

  if (windsurfDetected) {
    // Check 11: Windsurf skills junction
    const windsurfSkills = path.join(windsurfDir, 'skills');
    if (isLinkTo(windsurfSkills, hubSkills)) {
      passed_checks.push('Windsurf skills junction verified');
    } else {
      issues.push(`Windsurf skills junction missing or invalid: ${windsurfSkills} does not resolve to ${hubSkills}`);
    }

    // Check 12: Windsurf rules
    const globalRules = path.join(windsurfDir, 'memories', 'global_rules.md');
    if (
      (fs.existsSync(globalRules) && fs.statSync(globalRules).isFile()) ||
      (fs.existsSync(windsurfRulesLegacy) && fs.statSync(windsurfRulesLegacy).isFile())
    ) {
      passed_checks.push('Windsurf rules verified');
    } else {
      issues.push(`Windsurf rules missing: expected ${globalRules} or ${windsurfRulesLegacy}`);
    }
  }

  // Copilot CLI skills (personal skills live in ~/.copilot/skills)
  if (skillPlatform('copilot').detected(homeDir)) {
    const copilotSkills = path.join(homeDir, '.copilot', 'skills');
    if (isLinkTo(copilotSkills, hubSkills)) {
      passed_checks.push('Copilot skills junction verified');
    } else {
      issues.push(`Copilot skills junction missing or invalid: ${copilotSkills} does not resolve to ${hubSkills}`);
    }
  }

  // Check 13: MCP Registry Synchronization
  const mcpServersFile = path.join(hubDir, 'mcp', 'servers.json');
  if (!fs.existsSync(mcpServersFile)) {
    issues.push(`MCP hub registry missing: ${mcpServersFile} does not exist`);
  } else {
    const mcpStatus = getMcpStatus(homeDir, hubDir);
    if (!mcpStatus.hub.valid) {
      issues.push(`MCP hub registry file is invalid or corrupt JSON: ${mcpServersFile}`);
    }
    for (const id of MCP_PLATFORM_IDS) {
      const st = mcpStatus.platforms[id];
      if (st.installed && !st.valid) {
        issues.push(`${st.label} MCP configuration file is invalid or corrupt ${MCP_PLATFORMS[id].format === 'toml' ? 'TOML' : 'JSON'}: ${st.path}`);
      }
    }
    const platformsValid = MCP_PLATFORM_IDS.every((id) => !mcpStatus.platforms[id].installed || mcpStatus.platforms[id].valid);

    if (mcpStatus.in_sync) {
      passed_checks.push('MCP registry synchronized');
    } else if (mcpStatus.hub.valid && platformsValid) {
      const details: string[] = [];
      for (const id of MCP_PLATFORM_IDS) {
        const st = mcpStatus.platforms[id];
        if (st.missing.length) details.push(`missing in ${st.label}: ${st.missing.join(', ')}`);
        if (st.untracked.length) details.push(`untracked in ${st.label}: ${st.untracked.join(', ')}`);
        const drift = st.drifted.filter((n) => !st.conflicted.includes(n));
        if (drift.length) details.push(`drifted in ${st.label}: ${drift.join(', ')}`);
        if (st.conflicted.length) details.push(`conflict in ${st.label} (its own entry, not the hub's): ${st.conflicted.join(', ')}`);
      }
      issues.push(`MCP registry out of sync: ${details.join('; ') || 'discrepancies detected'}`);
    }
  }

  return { passed_checks, issues };
}

/**
 * Runs the diagnostic doctor check across all configured platforms and hub assets.
 * When options.fix is true, attempts auto-repair of detected issues.
 */
export function runDoctor(options?: DoctorOptions): DoctorResult {
  const homeDir = options?.homeDir || getHomeDir();
  const hubDir = options?.hubDir || getHubDir();

  let { passed_checks, issues } = performChecks(homeDir, hubDir);
  const repairs: string[] = [];

  if (options?.fix && issues.length > 0) {
    const agenthubJson = path.join(hubDir, 'agenthub.json');
    let manifestData: any = null;
    try {
      if (fs.existsSync(agenthubJson)) {
        manifestData = JSON.parse(fs.readFileSync(agenthubJson, 'utf-8'));
      }
    } catch {
      manifestData = null;
    }

    linkSkillsForClaude(homeDir, hubDir);
    linkSkillsForGemini(homeDir, hubDir);

    const codexDir = path.join(homeDir, '.codex');
    if (fs.existsSync(codexDir) && fs.statSync(codexDir).isDirectory()) {
      linkSkillsForCodex(homeDir, hubDir);
      projectCodexRules(homeDir, hubDir);
      projectCodexSkillManifests(hubDir);
    }

    const cursorTarget = manifestData?.platforms?.cursor?.path as string | undefined;
    const cursorDir = cursorTarget || path.join(homeDir, '.cursor');
    if (
      cursorTarget ||
      (fs.existsSync(cursorDir) && fs.statSync(cursorDir).isDirectory())
    ) {
      connectCursor(cursorTarget, homeDir, hubDir);
    }

    const windsurfTarget = manifestData?.platforms?.windsurf?.path as string | undefined;
    const codeiumDir = path.join(homeDir, '.codeium', 'windsurf');
    const dotWindsurfDir = path.join(homeDir, '.windsurf');
    if (
      windsurfTarget ||
      (fs.existsSync(codeiumDir) && fs.statSync(codeiumDir).isDirectory()) ||
      (fs.existsSync(dotWindsurfDir) && fs.statSync(dotWindsurfDir).isDirectory())
    ) {
      connectWindsurf(windsurfTarget, homeDir, hubDir);
    }

    if (skillPlatform('copilot').detected(homeDir)) linkSkillsForCopilot(homeDir, hubDir);

    projectGeminiRules(homeDir, hubDir);
    projectClaudeRules({ homeDir, hubDir });
    projectSubagents(homeDir, hubDir);

    const mcpServersFile = path.join(hubDir, 'mcp', 'servers.json');
    const mcpStatus = getMcpStatus(homeDir, hubDir);
    if (!fs.existsSync(mcpServersFile) || !mcpStatus.in_sync) {
      const syncRes = syncMcpServers({ homeDir, hubDir });
      repairs.push(...syncRes.actions);
    }

    repairs.push('Ran link_skills and projections across all platforms.');

    // Re-evaluate checks so passed_checks and issues reflect post-repair state
    const after = performChecks(homeDir, hubDir);
    passed_checks = after.passed_checks;
    issues = after.issues;
  }

  return {
    status: issues.length === 0 ? 'PASS' : 'WARN',
    passed_checks,
    issues,
    repairs,
  };
}
