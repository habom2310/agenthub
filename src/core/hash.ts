import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { byCodeUnit } from '../utils/sort.js';

/** Directories always left out of a folder hash (only directories: a file with such a name counts). */
export const HASH_SKIP: ReadonlySet<string> = new Set(['.git', 'node_modules']);
/** Also left out when hashing the sources of a local build (build output and caches). */
export const BUILD_HASH_SKIP: ReadonlySet<string> = new Set([
  ...HASH_SKIP,
  'dist',
  'build',
  'out',
  'target',
  '.venv',
  '__pycache__',
  '.next',
]);

/** First line of the Codex manifest agenthub writes into a skill, so it can be told from one the skill ships. */
export const GENERATED_MARK = '# generated by agenthub, not part of the skill';
// what earlier versions wrote, without the mark
const LEGACY_GENERATED = /^interface:\n {2}display_name: .*\n {2}short_description: .*\n {2}default_prompt: Use .* skill for this task\.\n$/;

/** True for the agents/openai.yaml that agenthub generated (and only that one). */
export function isGeneratedManifest(rel: string, full: string): boolean {
  if (rel !== 'agents/openai.yaml') return false;
  try {
    const text = fs.readFileSync(full, 'utf-8');
    return text.startsWith(GENERATED_MARK) || LEGACY_GENERATED.test(text);
  } catch {
    return false;
  }
}

/** The bytes with every CRLF turned into LF. */
function lfBytes(buf: Buffer): Buffer {
  if (!buf.includes(0x0d)) return buf;
  const out = Buffer.allocUnsafe(buf.length);
  let n = 0;
  for (let i = 0; i < buf.length; i++) if (!(buf[i] === 0x0d && buf[i + 1] === 0x0a)) out[n++] = buf[i];
  return out.subarray(0, n);
}

/**
 * Hashes the given files and symlinks of a folder (relative paths, any separator).
 * Paths are normalised to NFC with forward slashes and sorted in code-unit order.
 * Contents are raw bytes except that CRLF counts as LF, so a checkout with
 * core.autocrlf=true hashes the same as an LF one.
 * File modes and mtimes are ignored. A file is framed "path NUL size NUL bytes" and a
 * symlink "path NUL L NUL target NUL", so no two layouts collide.
 */
export function hashEntries(dir: string, rels: string[]): string {
  const items = rels.map((rel) => ({ rel, name: rel.split(path.sep).join('/').normalize('NFC') })).sort((a, b) => byCodeUnit(a.name, b.name));
  const hash = createHash('sha256');
  for (const { rel, name } of items) {
    const full = path.join(dir, rel);
    const st = fs.lstatSync(full);
    if (st.isSymbolicLink()) hash.update(`${name}\0L\0${fs.readlinkSync(full)}\0`);
    else if (st.isFile()) {
      const content = lfBytes(fs.readFileSync(full));
      hash.update(`${name}\0${content.length}\0`).update(content);
    }
  }
  return hash.digest('hex');
}

/** SHA-256 over a folder: see hashEntries. Directories in `skip` are left out, as is any file `skipFile` names. */
export function hashFolder(
  dir: string,
  skip: ReadonlySet<string> = HASH_SKIP,
  skipFile?: (rel: string, full: string) => boolean
): string {
  const rels: string[] = [];
  const walk = (rel: string): void => {
    for (const entry of fs.readdirSync(path.join(dir, rel), { withFileTypes: true })) {
      const next = rel ? `${rel}/${entry.name}` : entry.name;
      if (entry.isDirectory()) {
        if (!skip.has(entry.name)) walk(next);
      } else if ((entry.isFile() || entry.isSymbolicLink()) && !skipFile?.(next, path.join(dir, next))) rels.push(next);
    }
  };
  walk('');
  return hashEntries(dir, rels);
}

/** Hash of a vendored skill folder, as recorded in the lockfile. */
export const hashSkill = (dir: string): string => hashFolder(dir, HASH_SKIP, isGeneratedManifest);
